export function getRepertoireAnalysis(courseId, sectionIndex) {
  const sections = REPERTOIRE_ANALYSIS[courseId] ?? [];
  return sections[Math.max(0, Math.min(sectionIndex, sections.length - 1))] ?? null;
}

export function getPersonalizedRepertoireTransfer(analysis, preferences = []) {
  if (!analysis) return "Choose one audible mechanism and use it in a short phrase of your own.";
  const seed = analysis.transferSeed;
  if (preferences.includes("Film & game music")) return `Scoring study: use ${seed}. Present it once as safety, then change register, orchestration, or bass context so the same mechanism suggests uncertainty.`;
  if (preferences.includes("Ambient")) return `Ambient study: stretch ${seed} across a slower decay. Remove attacks until you can still hear the underlying voice-leading.`;
  if (preferences.includes("Songwriting")) return `Songwriting study: place a four-bar vocal phrase over ${seed}. Let the harmonic mechanism determine whether the line feels like verse, lift, or arrival.`;
  if (preferences.includes("Music production")) return `Production study: record ${seed} as a piano pass, then separate bass, inner motion, and focal voice into three layers without changing their musical jobs.`;
  if (preferences.includes("Improvisation")) return `Improvisation study: begin with ${seed}, repeat it once clearly, then vary only one property while preserving the cause-and-effect relationship.`;
  return `Composition study: build four bars from ${seed}. Keep the mechanism recognizable, then change its ending to create a second phrase.`;
}

export function repertoireAnalysisCount() {
  return Object.values(REPERTOIRE_ANALYSIS).reduce((total, sections) => total + sections.length, 0);
}
